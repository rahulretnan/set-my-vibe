import fs from 'node:fs';
import path from 'node:path';
import { quote } from './core.mjs';
export function shellSnippet(ctx) {
  return `# Generated by set-my-vibe. No credentials belong here.
export SET_MY_VIBE_HOME=${quote(ctx.data)}
export PATH="$HOME/.local/bin:$SET_MY_VIBE_HOME/npm/bin:$SET_MY_VIBE_HOME/runtime/bin:$HOME/.bun/bin:$HOME/.cargo/bin:$PATH"
for vibe_brew in /opt/homebrew/bin/brew /home/linuxbrew/.linuxbrew/bin/brew /usr/local/bin/brew; do
  if [ -x "$vibe_brew" ]; then eval "$("$vibe_brew" shellenv)"; break; fi
done
unset vibe_brew
export NVM_DIR="\${NVM_DIR:-$HOME/.nvm}"
[ ! -s "$NVM_DIR/nvm.sh" ] || . "$NVM_DIR/nvm.sh"
if command -v direnv >/dev/null 2>&1; then
  if [ -n "\${ZSH_VERSION:-}" ]; then eval "$(direnv hook zsh)"
  elif [ -n "\${BASH_VERSION:-}" ]; then eval "$(direnv hook bash)"; fi
fi
`;
}
export function configureShell(ctx,{dryRun=false}={}) {
  if(/[\r\n]/.test(ctx.data)) throw Error('Installation path must not contain newlines.');
  const snippet=path.join(ctx.data,'shell.sh');
  const line=`[ ! -f ${quote(snippet)} ] || . ${quote(snippet)}`;
  // Never read or rewrite existing dotfiles. The marker is a separate public-data file.
  const targets=[path.join(ctx.home,'.zshrc'),path.join(ctx.home,'.bashrc')];
  if(dryRun) return {snippet,targets,content:shellSnippet(ctx),line};
  fs.mkdirSync(ctx.data,{recursive:true,mode:0o700});
  const marker=path.join(ctx.data,'shell-configured.json');
  for(const f of [snippet,marker,...targets]) {
    try { if(fs.lstatSync(f).isSymbolicLink()) throw Error(`Refusing to modify symlink: ${f}. Add the documented source line yourself.`); } catch(e) { if(e.code!=='ENOENT') throw e; }
  }
  let completed=[];
  try { completed=JSON.parse(fs.readFileSync(marker,'utf8')); } catch(e) { if(e.code!=='ENOENT') throw Error('Invalid shell integration marker; refusing to append duplicate hooks.'); }
  fs.writeFileSync(snippet,shellSnippet(ctx),{mode:0o600});
  for(const f of targets) {
    if(completed.includes(f) && fs.existsSync(f)) continue;
    fs.appendFileSync(f,`\n# set-my-vibe shell integration\n${line}\n`,{mode:0o600});
    completed.push(f);
    fs.writeFileSync(marker,JSON.stringify([...new Set(completed)]),{mode:0o600});
  }
  return {snippet,targets};
}
